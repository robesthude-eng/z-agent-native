/**
 * Разрешения, на которые автоподтверждение уже ответило.
 *
 * Очередь для этого не годится: успешный ответ УБИРАЕТ запрос из очереди, и
 * повторно доставленное SSE-событие (переподключение стрима) снова выглядело
 * бы как новое. Второй ответ на то же разрешение сервер отвергает, а
 * обработчик ошибки вернул бы запрос в очередь — пользователь увидел бы
 * карточку на действие, которое уже разрешено.
 *
 * Единственная операция — `claim`, и это не украшение. Прежний код проверял
 * `has` и следом делал `add` двумя шагами; между ними ничего не менялось лишь
 * потому, что оба стоят в одном синхронном блоке. Свойство «проверили и
 * заняли» лучше выражать одним вызовом, чем полагаться на то, что никто не
 * вставит await посередине.
 */
export class PermissionDedup {
  private answered = new Set<string>();

  /**
   * Занять разрешение под ответ.
   *
   * @returns true — заняли сейчас, отвечать можно;
   *          false — на него уже отвечали, повтор игнорируем.
   */
  claim(permissionId: string): boolean {
    if (this.answered.has(permissionId)) return false;
    this.answered.add(permissionId);
    return true;
  }

  /** Отвечали ли уже на это разрешение (без занятия). */
  wasAnswered(permissionId: string): boolean {
    return this.answered.has(permissionId);
  }

  /** Забыть всё: изоляция тестов. */
  reset(): void {
    this.answered.clear();
  }
}

/** Общий на приложение экземпляр — как `sessionFsm` и `turnSettle`. */
export const permissionDedup = new PermissionDedup();
