import { t } from "@/i18n";
/**
 * Вердикт хода — единственное, что интерфейсу разрешено знать о завершении.
 *
 * Этап 1.4c. До него `messagesSlice.send()` держал собственный арбитраж: SSE-
 * резолвер, HTTP-поллер с окном стабильности и предохранительный таймаут на
 * 15 минут. Три источника, сведённые в клиенте, — то самое, что инвариант I-30
 * запрещает: «UI не вычисляет завершение хода самостоятельно».
 *
 * Почему это не придирка к архитектуре. Пока арбитров два, они расходятся, и
 * расходятся молча: сервер считает ход завершённым, клиент ещё крутит спиннер,
 * или наоборот. Отладка такого расхождения упирается в вопрос «чьё состояние
 * правильное», у которого нет ответа. Один арбитр устраняет сам вопрос.
 *
 * Здесь только типы и чистые функции над ответом сервера. Ожидание финала,
 * статусы и обработка ошибок остаются в сторе: их нельзя проверить без стора, а
 * вот решение «что этот вердикт означает для интерфейса» — можно, и оно
 * проверяется отдельно.
 */

/**
 * Флаг выката на стороне клиента.
 *
 * Отдельный от серверных: сервер может вести учёт ходов, а интерфейс при этом
 * ещё читать завершение по-старому — именно так этап и выкатывается. Обратное
 * сочетание бесполезно, и опрос это замечает: если сервер отвечает
 * `orchestrator: false`, интерфейс не ждёт вердикта, которого не будет.
 *
 * Значение читается из окружения сборки: Vite подставляет его на этапе
 * компиляции, поэтому переключение требует пересборки фронтенда — в отличие от
 * серверных флагов, которые меняются перезапуском.
 */
export function isVerdictSourceEnabled(): boolean {
  try {
    return import.meta.env?.VITE_TURN_VERDICT_SOURCE !== "0";
  } catch {
    return true;
  }
}

/**
 * Интервал опроса вердикта.
 *
 * Совпадает с интервалом сверки на сервере (`RECONCILE_INTERVAL_MS` = 3 с) и не
 * случайно: спрашивать чаще, чем сервер пересматривает решение, — значит
 * получать тот же ответ и жечь запросы.
 */
export const VERDICT_POLL_MS = 3_000;

/** Состояния хода из `contracts/LIFECYCLES.md`. */
export type TurnLifecycle =
  | "draft"
  | "queued"
  | "submitting"
  | "running"
  | "waiting_permission"
  | "waiting_user_input"
  | "reconciling"
  | "stuck"
  | "completed"
  | "failed"
  | "cancelled";

/** Вердикт наружу — пять значений из `EXECUTION_TRUTH.md` §2. */
export type TurnVerdict =
  | "completed"
  | "failed"
  | "cancelled"
  | "reconciling"
  | "stuck";

/** Проекция хода, которую отдаёт `GET /api/session/:id/turn`. */
export interface TurnProjection {
  turnId: string;
  lifecycle: TurnLifecycle;
  verdict: TurnVerdict | null;
  since: number;
  /** Причина последнего решения. Для человека — в логах и разборе, не в UI. */
  reason: string | null;
}

/** Ответ маршрута целиком. */
export interface TurnStateResponse {
  /** `null` — активного хода нет. Это ответ, а не ошибка. */
  turn: TurnProjection | null;
  /** Включён ли оркестратор на сервере. */
  orchestrator: boolean;
}

/**
 * Что интерфейс должен делать с ходом.
 *
 * Намеренно НЕ повторяет состояния хода один к одному. Интерфейсу не нужно
 * знать разницу между `submitting` и `running` — и там и там идёт работа. А вот
 * разницу между «работает» и «мы не знаем» знать обязательно: она и есть то,
 * ради чего вводился вердикт `stuck`.
 */
export type TurnDisposition =
  /** Ход идёт. Показываем работу. */
  | "busy"
  /** Ход ждёт человека: разрешение или ответ на вопрос. */
  | "waiting"
  /** Ход закончился — успешно или нет, интерфейс в обоих случаях свободен. */
  | "settled"
  /** Ход завершился ошибкой: свободен, но об этом надо сказать. */
  | "failed"
  /** Состояние неизвестно. Требует спокойного явного представления (I-32). */
  | "stuck";

/**
 * Свести проекцию к тому, что делать интерфейсу.
 *
 * `reconciling` считается работой, а не отдельным видимым состоянием, и это
 * решение, а не упрощение. Сверка длится окно стабилизации — секунды, — и в
 * половине случаев кончается возвратом в `running`. Показать её пользователем
 * значило бы мигать статусом на каждом промежуточном маркере.
 *
 * @param turn проекция или `null`, если активного хода нет
 */
export function dispositionOf(turn: TurnProjection | null): TurnDisposition {
  if (!turn) return "settled";
  switch (turn.lifecycle) {
    case "waiting_permission":
    case "waiting_user_input":
      return "waiting";
    case "completed":
    case "cancelled":
      return "settled";
    case "failed":
      return "failed";
    case "stuck":
      return "stuck";
    default:
      // draft, queued, submitting, running, reconciling — работа идёт.
      return "busy";
  }
}

/**
 * Закончился ли ход.
 *
 * `stuck` НЕ считается завершением, и это главное отличие от прежнего
 * поведения. Раньше истечение предохранительного таймаута снимало busy —
 * то есть «мы не знаем» выдавалось за «всё готово». Теперь такой ход остаётся
 * незакрытым и получает явное представление.
 */
export function isSettled(turn: TurnProjection | null): boolean {
  const d = dispositionOf(turn);
  return d === "settled" || d === "failed";
}

/**
 * Строка для пользователя, когда состояние неопределённое (I-32).
 *
 * Требование контракта: не бесконечный спиннер, а короткая честная фраза и
 * одно понятное действие. Скрытая неопределённость ничем не отличается от
 * зависшего интерфейса — именно так это и выглядело до сих пор.
 */
export const STUCK_NOTICE = t("turn_verdict.ne_udalos_podtverdit_sostoyanie_otveta");

/** Подпись действия для состояния `stuck`. */
export const STUCK_ACTION = t("turn_verdict.proverit_snova");

/**
 * Все виды диспозиции — данными, а не только типом.
 *
 * Нужно, чтобы проверку I-32 можно было вести перебором. Тип существует лишь
 * во время сборки, и добавленное шестое значение прошло бы мимо любого теста;
 * список же зафиксирован тестом, поэтому новое значение обязывает решить, как
 * оно показывается, — а не просто появляется.
 */
export const TURN_DISPOSITIONS: readonly TurnDisposition[] = [
  "busy",
  "waiting",
  "settled",
  "failed",
  "stuck",
];

/**
 * Как показывается неопределённое состояние (I-32).
 *
 * Прежняя формулировка инварианта — «любое неопределённое состояние имеет
 * спокойное представление» — не поддавалась проверке: у слова «спокойное» не
 * было критерия. По правилу самого проекта это дефект формулировки, а не
 * пробел в тестах.
 *
 * Критерий такой: неопределённость обязана быть НАЗВАНА словами и предлагать
 * действие. Не индикатор без подписи, не пустота, не вид успеха. Скрытая
 * неопределённость ничем не отличается от зависшего интерфейса — именно так это
 * и выглядело до сих пор.
 *
 * `null` означает «состояние определено, объяснять нечего». Из пяти диспозиций
 * неопределённой является одна — `stuck`; `busy` и `waiting` определены (идёт
 * работа, ждём человека), `settled` и `failed` — исходы.
 *
 * @returns текст и подпись действия, либо `null`
 */
export function undefinedStatePresentation(
  disposition: TurnDisposition,
): { notice: string; action: string } | null {
  if (disposition !== "stuck") return null;
  return { notice: STUCK_NOTICE, action: STUCK_ACTION };
}

/**
 * Что показывает индикатор хода.
 *
 * `"unknown"` — не состояние хода, а признак отсутствия проекции: после
 * перезагрузки страницы поллер вердикта не запущен, потому что он живёт внутри
 * `send()`. В этом случае вызывающий обязан решать по прежнему признаку
 * (`status === "busy"`), иначе индикатор исчезнет посреди идущего ответа.
 */
export type TurnIndicator =
  | { kind: "hidden" }
  | { kind: "working" }
  | { kind: "unresolved"; notice: string; action: string }
  | { kind: "unknown" };

/**
 * Проекция диспозиции в индикатор (I-32, этап 3.2).
 *
 * Решения, принятые не здесь, а согласованные отдельно, — они видимы
 * пользователю, и выводить их из контракта нельзя:
 *
 *   `waiting` НЕ показывается индикатором. У ожидания есть свой интерфейс —
 *   `PermissionDialog`; второй индикатор рядом с ним спорил бы с диалогом за
 *   внимание и сообщал бы то же самое дважды.
 *
 *   `reconciling` не имеет собственного вида и попадает в `working` через
 *   `dispositionOf`. Сверка длится секунды и в половине случаев кончается
 *   возвратом в `running`: отдельный ярлык мигал бы на каждом промежуточном
 *   маркере.
 *
 *   `failed` скрывает индикатор: ошибка принадлежит сообщению и показывается на
 *   нём. Дублировать её в индикаторе значило бы сообщить об одной неудаче в двух
 *   местах.
 *
 * Функция полна по `TURN_DISPOSITIONS` — это проверяется тестом. Диспозиция без
 * своего вида проходила бы молча и не показывала ничего.
 */
export function indicatorFor(
  disposition: TurnDisposition | null,
): TurnIndicator {
  if (disposition === null) return { kind: "unknown" };
  switch (disposition) {
    case "busy":
      return { kind: "working" };
    case "stuck": {
      const shown = undefinedStatePresentation("stuck");
      // shown здесь никогда не null, но проверка оставлена: связь с
      // `undefinedStatePresentation` должна остаться единственной, иначе текст
      // для `stuck` заведётся в двух местах и разойдётся.
      return shown
        ? { kind: "unresolved", notice: shown.notice, action: shown.action }
        : { kind: "hidden" };
    }
    case "waiting":
    case "settled":
    case "failed":
      return { kind: "hidden" };
    default:
      // Недостижимо при полном переборе, но диспозиция могла появиться новой.
      // Тогда честнее ничего не показывать, чем показать работу, которой нет.
      return { kind: "hidden" };
  }
}

/**
 * Почему нельзя отправить сообщение прямо сейчас (этап 2.1).
 *
 * `null` — можно. Отправка во время работы агента разрешена и остаётся такой:
 * композер ставит подобные сообщения в очередь, и это привычное поведение.
 * Блокируется ровно ожидание человека.
 *
 * Причина: пока агент ждёт разрешения или ответа, отправка начинает ВТОРОЙ ход
 * при приостановленном первом. Условие этапа 2.1 — «прерывания не рвут
 * непрерывность хода», и это ровно тот разрыв.
 *
 * Оба вида ожидания дают одну причину нарочно: пользователю здесь не важна
 * разница между «ждёт разрешения» и «ждёт ответа» — важно, что ход не
 * продолжится, пока он не ответит. Что именно спрашивают, видно в самом
 * прерывании.
 *
 * Отсутствие проекции тоже даёт `null`, и это осознанно: пока оркестратор
 * выключен, проекции нет, и запрет означал бы поведение, которого сегодня нет.
 */
export function sendBlockReason(
  disposition: TurnDisposition | null,
): string | null {
  if (disposition !== "waiting") return null;
  return t("turn_verdict.snachala_otvette_agentu_on_zhdet_i");
}

/**
 * Разобрать ответ маршрута, не доверяя его форме.
 *
 * Сервер может ответить старой версией (маршрута ещё нет — тогда прокси отдаст
 * что-то от движка) или новой с полем, которого мы не ждём. Ни то ни другое не
 * должно ронять отправку сообщения, поэтому неузнанный ответ означает «данных
 * нет», а не исключение.
 */
export function parseTurnState(raw: unknown): TurnStateResponse | null {
  if (typeof raw !== "object" || raw === null) return null;
  const obj = raw as Record<string, unknown>;
  if (!("turn" in obj)) return null;
  const orchestrator = obj.orchestrator === true;
  if (obj.turn === null) return { turn: null, orchestrator };
  if (typeof obj.turn !== "object") return null;

  const t = obj.turn as Record<string, unknown>;
  if (typeof t.turnId !== "string" || typeof t.lifecycle !== "string") {
    return null;
  }
  return {
    orchestrator,
    turn: {
      turnId: t.turnId,
      lifecycle: t.lifecycle as TurnLifecycle,
      verdict: (typeof t.verdict === "string"
        ? t.verdict
        : null) as TurnVerdict | null,
      since: typeof t.since === "number" ? t.since : 0,
      reason: typeof t.reason === "string" ? t.reason : null,
    },
  };
}
