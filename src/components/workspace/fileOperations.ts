/**
 * Решения об операциях над файлами воркспейса: разрешена ли операция, куда
 * переезжает файл при переименовании, что становится с открытым редактором,
 * куда ведёт скачивание.
 *
 * Этап 3.1, вторая часть после дерева. Разрезано по тому же признаку:
 * решения выносятся и закрываются перебором, движение разметки идёт отдельной
 * правкой. Всё, что ниже, жило внутри `Workspace.tsx` — обработчиками, которые
 * не поднимаются ни одним тестом, потому что для этого нужен компонент.
 *
 * Перенос дословный с двумя исключениями, и оба — дефекты, а не улучшения:
 *
 * 1. Операция над ПАПКОЙ не замечала открытого внутри неё файла. Условие было
 *    `activeFile.path === node.path`, то есть совпадение целиком. Переименуй
 *    папку `src`, держа открытым `src/a.ts`, — редактор оставался на старом
 *    пути, и следующее сохранение воссоздавало и файл, и папку, которую
 *    пользователь только что переименовал. Кнопки переименования и удаления
 *    стоят на папках наравне с файлами (`WorkspaceTree.tsx`), так что ветка
 *    достижима, а не гипотетична.
 * 2. Скачивание не должно собирать URL без сессии: native runtime не может
 *    определить изолированный workspace без sessionId. Сегодня ветка почти
 *    недостижима — дерево рисуется только при выбранном чате, — но fail-closed
 *    правило всё равно закреплено здесь.
 */

import { isTmpSession } from "../../lib/ids";
import { parentDir } from "./fileDecisions";

/** Почему операция над файлами недоступна. `null` — доступна. */
export type OperationBlock = "no_chat" | "draft_chat" | null;

export interface OperationGate {
  allowed: boolean;
  reason: OperationBlock;
  /** Текст для пользователя. Пусто ровно тогда, когда операция доступна. */
  explanation: string;
}

/**
 * Можно ли выполнять операции с файлами в этом чате.
 *
 * Условие `!currentID || isTmpSession(currentID)` стояло в коде восемь раз —
 * в каждом обработчике и в `disabled` каждой кнопки — и всюду молча. Молчание
 * здесь того же рода, что запрещает I-31 неактивной кнопке: пользователь видит
 * погасший интерфейс и не знает, ждать ему или что-то сделать.
 *
 * Двух причин достаточно, и они разные по смыслу: чат не выбран (сделать
 * нечего, воркспейса не существует) и чат ещё черновик (воркспейс появится
 * с первым сообщением). Сливать их в одну строку значило бы советовать
 * «выберите чат» тому, кто уже в нём стоит.
 *
 * Черновик здесь НЕ материализуется, в отличие от прикрепления файла
 * (`sessionActionPrep`, I-21). Разница содержательная: прикрепление — это
 * действие пользователя в чате, оно и должно чат создавать. Открытая панель
 * файлов сама по себе намерения не выражает, и заводить сессию за просмотр
 * значило бы плодить пустые чаты от одного клика по «Файлы проекта».
 */
export function operationGate(sessionId?: string | null): OperationGate {
  if (!sessionId) {
    return {
      allowed: false,
      reason: "no_chat",
      explanation: "Выберите или создайте чат",
    };
  }
  if (isTmpSession(sessionId)) {
    return {
      allowed: false,
      reason: "draft_chat",
      explanation: "Воркспейс появится после первого сообщения",
    };
  }
  return { allowed: true, reason: null, explanation: "" };
}

/**
 * Лежит ли путь внутри узла или совпадает с ним.
 *
 * Одна функция на оба последствия операции — переезд редактора и его закрытие.
 * Два условия одного смысла разошлись бы молча, а разойтись им есть куда:
 * граница поддерева проходит по разделителю, и запрет по голому префиксу
 * захватил бы `project-ui-notes.md` вместе с `project-ui/`. Ровно эта ошибка
 * уже закрыта тестом в `fileDecisions`.
 */
export function isInsideOrSelf(candidate: string, target: string): boolean {
  if (!target) return false;
  return candidate === target || candidate.startsWith(`${target}/`);
}

export type RenamePlan =
  | { kind: "noop"; reason: "empty" | "unchanged" }
  | { kind: "rename"; to: string };

/**
 * Куда переезжает узел при переименовании.
 *
 * Имя вводится без пути, а путь достраивается из родителя: поле правит
 * последний сегмент, и подставлять туда что-то ещё пользователь не просил.
 *
 * **Обход каталогов здесь НЕ отсекается**, и это то же решение, что записано
 * рядом для ссылки превью. Имя с `/` или `..` уходит на сервер как есть,
 * настоящая граница — `buildSafeWorkspacePath` (I-02), и она закрыта тестом.
 * Вторая проверка на клиенте создала бы иллюзию, из-за которой серверную
 * однажды сочтут лишней.
 *
 * Два исхода «ничего не делать» названы по отдельности, потому что означают
 * разное: пустое поле — это отказ от переименования (в том числе по Escape и
 * по потере фокуса), а совпадение с прежним путём — успешный ввод того же
 * имени. Первое молчит, второе тоже, но повод у них разный, и при следующей
 * правке их легко перепутать.
 */
export function renamePlan(fromPath: string, rawName: string): RenamePlan {
  const name = rawName.trim();
  if (!name) return { kind: "noop", reason: "empty" };
  const dir = parentDir(fromPath);
  const to = dir ? `${dir}/${name}` : name;
  if (to === fromPath) return { kind: "noop", reason: "unchanged" };
  return { kind: "rename", to };
}

/**
 * Где оказывается открытый файл после переименования узла.
 *
 * `null` — редактор не трогаем. Строка — новый путь того же файла.
 *
 * Переезд, а не закрытие: файл никуда не делся, и закрывать его значило бы
 * терять несохранённый черновик за чужое действие. Сохранение берёт путь из
 * `activeFile`, поэтому оставить старый — это записать файл обратно по пути,
 * которого больше нет: воскресает и файл, и папка.
 */
export function editorAfterRename(
  activePath: string | null | undefined,
  fromPath: string,
  toPath: string,
): string | null {
  if (!activePath) return null;
  if (!isInsideOrSelf(activePath, fromPath)) return null;
  return `${toPath}${activePath.slice(fromPath.length)}`;
}

/**
 * Закрывается ли открытый файл после удаления узла.
 *
 * Закрытие теряет несохранённый черновик, и это осознанно: сохранять его
 * некуда — файла больше нет, а запись воссоздала бы удалённое. Поведение
 * ровно то же, что было для точного совпадения; расширяется только область,
 * на которую оно распространяется.
 */
export function editorClosedByDelete(
  activePath: string | null | undefined,
  deletedPath: string,
): boolean {
  if (!activePath) return false;
  return isInsideOrSelf(activePath, deletedPath);
}

/**
 * Свойства кнопки панели файлов: неактивна ли и что сказать при наведении.
 *
 * Форма повторяет `capabilityGate` (`src/api/capabilities.ts`) намеренно —
 * там же принят и сам приём показа причины через `title` неактивной кнопки, и
 * заводить рядом второй способ значило бы объяснять одно и то же двумя
 * разными деталями интерфейса.
 *
 * Одно отличие от прообраза названо явно. `capabilityGate` при отсутствующем
 * чате причину НЕ подставляет: «окружение ещё не создано» звучало бы поломкой
 * там, где пользователь просто не выбрал чат. Здесь подставляет, потому что
 * формулировка ровно про это и есть — «выберите или создайте чат» и
 * выполнима, и верна. Правило одно и то же: причина обязана быть верной и
 * выполнимой, а не просто присутствовать.
 *
 * Занятость проверяется ПОСЛЕ шлюза. Порядок значим: во время загрузки папки
 * в черновике верна обе причины сразу, и сказать надо ту, которая объясняет,
 * почему кнопка не заработает сама — идущая загрузка кончится, отсутствие
 * чата нет.
 */
export function panelButtonGate(facts: {
  sessionId?: string | null | undefined;
  fallbackTitle: string;
  busy?: boolean;
  busyTitle?: string;
}): { disabled: boolean; title: string } {
  const gate = operationGate(facts.sessionId);
  if (!gate.allowed) return { disabled: true, title: gate.explanation };
  if (facts.busy) {
    return { disabled: true, title: facts.busyTitle ?? facts.fallbackTitle };
  }
  return { disabled: false, title: facts.fallbackTitle };
}

/**
 * Тот же шлюз в форме признака типа — для мест, где решение не показывается,
 * а только исполняется.
 *
 * Две формы одного правила, а не два правила: `operationGate` нужен там, где
 * отказ надо объяснить, `workspaceOperable` — там, где после проверки сразу
 * идёт вызов с идентификатором сессии. Сужение типа существенно: без него
 * каждый вызов требовал бы второй проверки на `null` рядом с первой, и
 * рассогласование этой пары — ровно тот класс ошибок, который здесь и
 * закрывается. Совпадение обеих форм закреплено перебором.
 *
 * Скачивание ходит через него же. Без sessionId native runtime не выбирает
 * workspace, поэтому ссылка не создаётся вовсе. Сам URL собирает
 * `workspaceDownloadUrl` из `api/client` — там же он используется для
 * файл-чипов в переписке, чтобы правило оставалось единым.
 */
export function workspaceOperable(
  sessionId?: string | null,
): sessionId is string {
  return operationGate(sessionId).allowed;
}

/**
 * Доля выполненной загрузки папки, целые проценты.
 *
 * Знаменатель — число файлов, а не батчей: `total` нулевой до первого выбора
 * папки, и деление на него дало бы `NaN` в ширине полосы, то есть полосу,
 * исчезающую в момент старта загрузки.
 */
export function uploadPercent(done: number, total: number): number {
  if (!Number.isFinite(done) || !Number.isFinite(total) || total <= 0) return 0;
  const pct = Math.round((done / total) * 100);
  return Math.min(100, Math.max(0, pct));
}

/**
 * Разбиение списка файлов на батчи загрузки.
 *
 * Батч существует потому, что папка бывает в тысячи файлов, а `multipart` со
 * всеми сразу упирается в лимит тела запроса (`server/middleware.mjs`).
 * Свойство, которое здесь важно: объединение батчей равно исходному списку в
 * том же порядке — потерянный при разбиении файл не заметил бы никто, загрузка
 * всё равно отчиталась бы успехом.
 */
export function uploadBatches<T>(files: T[], size: number): T[][] {
  const step = Math.max(1, Math.floor(size));
  const out: T[][] = [];
  for (let i = 0; i < files.length; i += step) {
    out.push(files.slice(i, i + step));
  }
  return out;
}
