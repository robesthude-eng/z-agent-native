/**
 * Решения о синхронизации дерева воркспейса: чей результат применять, когда
 * опрашивать сервер и что делать с ошибкой.
 *
 * Этап 3.1, третья часть. Всё это жило внутри `Workspace.tsx` двумя
 * обработчиками и эффектом с таймером — то есть в местах, которые не поднять
 * тестом, потому что для этого нужен компонент и настоящее время.
 *
 * Правило поколений — самое дорогое из трёх и единственное, которое уже
 * ломалось. Оно записано в коде комментарием «фоновый опрос не должен
 * инвалидировать ручной refresh», и до сих пор ничто не мешало этому
 * комментарию разойтись с кодом.
 */

/**
 * Пауза между фоновыми опросами файловой системы.
 *
 * Значение взято из кода как есть. Порог назван числом здесь, а не в теле
 * эффекта, по той же причине, по которой пороги арбитража собраны в одном
 * месте: «интервал забыли» и «интервал такой» должны быть различимы.
 */
export const POLL_INTERVAL_MS = 8000;

/** Кто заказал загрузку дерева. */
export type LoadKind = "manual" | "background";

/**
 * Поколение загрузки после начала новой.
 *
 * Ручная перезагрузка поколение бампает и тем отменяет всё, что было в пути:
 * пользователь нажал «Обновить», значит прежний ответ ему уже не нужен.
 * Фоновый опрос не бампает — иначе тик таймера, пришедший через секунду после
 * нажатия, отменял бы ручную перезагрузку, и кнопка вела бы себя как случайная.
 */
export function nextGeneration(current: number, kind: LoadKind): number {
  return kind === "manual" ? current + 1 : current;
}

/**
 * Применять ли пришедший результат.
 *
 * Одна функция на оба пути. Разъедься они — фоновый ответ записал бы дерево
 * чужой или устаревшей сессии поверх свежего, и наружу это выглядело бы как
 * «файлы то появляются, то исчезают»: диагноз, по которому никто не найдёт
 * причину.
 *
 * Сравнение строгое: поколение, снятое до запроса, обязано совпасть с текущим
 * на момент ответа. Больше оно стать не может, меньше — значит между стартом и
 * ответом была ручная перезагрузка или смена чата.
 */
export function acceptsResult(startedAt: number, current: number): boolean {
  return startedAt === current;
}

/**
 * Стоит ли сейчас опрашивать сервер.
 *
 * Три условия, и все три — про то, что опрос бессмысленен, а не вреден.
 * Закрытая панель ничего не показывает; скрытая вкладка не показывает вообще
 * ничего; черновик и отсутствие чата не имеют воркспейса на сервере.
 *
 * Возврат на вкладку опрашивает сразу, не дожидаясь тика: восемь секунд
 * несвежего дерева после переключения окна выглядят как подвисание, хотя
 * данные уже есть.
 */
export function shouldPoll(facts: {
  panelOpen: boolean;
  documentHidden: boolean;
  sessionReady: boolean;
}): boolean {
  return facts.panelOpen && !facts.documentHidden && facts.sessionReady;
}

/**
 * Что делать с ошибкой загрузки дерева.
 *
 * Разные пути и разные исходы, и разница не в аккуратности. Ручная
 * перезагрузка ошибку ПОКАЗЫВАЕТ: пользователь нажал кнопку и ждёт ответа,
 * молчание он прочитает как «файлов нет». Фоновый опрос ошибку глотает:
 * сеть моргнула между тиками, дерево на экране всё ещё верное, и красная
 * плашка поверх него сообщила бы о поломке, которой пользователь не заметил
 * бы иначе.
 */
export function errorDisposition(kind: LoadKind): "show" | "swallow" {
  return kind === "manual" ? "show" : "swallow";
}
